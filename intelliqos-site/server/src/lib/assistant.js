function isAiConfigured() {
  return Boolean(process.env.ANTHROPIC_API_KEY);
}

async function aiAnswer(message, history) {
  const model = process.env.ANTHROPIC_MODEL || 'claude-haiku-4-5-20251001';

  const messages = (history || [])
    .slice(-6) // не тащим бесконечную историю — контролируем стоимость запроса
    .map((h) => ({ role: h.role === 'assistant' ? 'assistant' : 'user', content: String(h.content).slice(0, 1000) }));
  messages.push({ role: 'user', content: String(message).slice(0, 1000) });

  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': process.env.ANTHROPIC_API_KEY,
      'anthropic-version': '2023-06-01'
    },
    body: JSON.stringify({
      model,
      max_tokens: 300,
      system: CATALOG_TEXT,
      messages
    })
  });

  if (!res.ok) {
    const text = await res.text().catch(() => '');
    throw new Error(`Anthropic API ${res.status}: ${text.slice(0, 200)}`);
  }

  const data = await res.json();
  const reply = (data.content || []).map((b) => b.text || '').join('').trim();
  return reply || ruleBasedAnswer(message);
}

async function getReply(message, history) {
  if (isAiConfigured()) {
    try {
      const reply = await aiAnswer(message, history);
      return { reply, mode: 'ai' };
    } catch (e) {
      console.error('Assistant AI error, falling back to rules:', e.message);
      return { reply: ruleBasedAnswer(message), mode: 'rules' };
    }
  }
  return { reply: ruleBasedAnswer(message), mode: 'rules' };
}

module.exports = { getReply, ruleBasedAnswer, isAiConfigured };
